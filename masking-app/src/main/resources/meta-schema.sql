-- Meta DB (H2) schema. Runs on every connection via INIT=RUNSCRIPT, so everything is IF NOT EXISTS.

CREATE TABLE IF NOT EXISTS db_connection (
    id            BIGINT AUTO_INCREMENT PRIMARY KEY,
    name          VARCHAR(100)  NOT NULL,
    host          VARCHAR(255)  NOT NULL,
    port          INT           NOT NULL,
    database_name VARCHAR(128)  NOT NULL,
    username      VARCHAR(128)  NOT NULL,
    password_enc  VARCHAR(1024),
    options       VARCHAR(512),
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS masking_job (
    id            BIGINT AUTO_INCREMENT PRIMARY KEY,
    name          VARCHAR(100)  NOT NULL,
    connection_id BIGINT        NOT NULL,
    source_table  VARCHAR(128)  NOT NULL,
    pk_column     VARCHAR(128)  NOT NULL,
    target_table  VARCHAR(128)  NOT NULL,
    chunk_size    INT           NOT NULL DEFAULT 500,
    cron          VARCHAR(64),
    enabled       BOOLEAN       NOT NULL DEFAULT TRUE,
    policies      VARCHAR(400)  NOT NULL,
    hash_salt     VARCHAR(64)   NOT NULL,
    -- 대화 문맥(2단계): 통화 ID·화자 컬럼, 상담사 화자 값. 모두 NULL 이면 사용 안 함. 이전 DB 는 MetaMigration 이 추가
    dialog_call_column    VARCHAR(128),
    dialog_speaker_column VARCHAR(128),
    dialog_agent_value    VARCHAR(50),
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS masking_column (
    id           BIGINT AUTO_INCREMENT PRIMARY KEY,
    job_id       BIGINT       NOT NULL,
    column_name  VARCHAR(128) NOT NULL,
    col_mode     VARCHAR(10)  NOT NULL,
    entity_types VARCHAR(200),
    ordinal      INT          NOT NULL
);

CREATE TABLE IF NOT EXISTS job_watermark (
    job_id     BIGINT PRIMARY KEY,
    last_pk    VARCHAR(255),
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS job_execution (
    id              BIGINT AUTO_INCREMENT PRIMARY KEY,
    job_id          BIGINT       NOT NULL,
    trigger_type    VARCHAR(10)  NOT NULL,
    status          VARCHAR(12)  NOT NULL,
    started_at      TIMESTAMP    NOT NULL,
    ended_at        TIMESTAMP,
    read_count      BIGINT       NOT NULL DEFAULT 0,
    masked_rows     BIGINT       NOT NULL DEFAULT 0,
    span_count      BIGINT       NOT NULL DEFAULT 0,
    written_count   BIGINT       NOT NULL DEFAULT 0,
    start_pk        VARCHAR(255),
    end_pk          VARCHAR(255),
    error_message   VARCHAR(1000)
);

CREATE TABLE IF NOT EXISTS audit_log (
    id         BIGINT AUTO_INCREMENT PRIMARY KEY,
    actor      VARCHAR(100) NOT NULL,
    action     VARCHAR(50)  NOT NULL,
    target     VARCHAR(200),
    outcome    VARCHAR(20)  NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Spring Batch 6.0.5 메타 테이블(schema-h2.sql 을 IF NOT EXISTS 로 바꿈). 버전을 올리면 공식 스키마와 다시 맞춘다

CREATE TABLE IF NOT EXISTS BATCH_JOB_INSTANCE (
	JOB_INSTANCE_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	VERSION BIGINT,
	JOB_NAME VARCHAR(100) NOT NULL,
	JOB_KEY VARCHAR(32) NOT NULL,
	constraint JOB_INST_UN unique (JOB_NAME, JOB_KEY)
) ;

CREATE TABLE IF NOT EXISTS BATCH_JOB_EXECUTION (
	JOB_EXECUTION_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	VERSION BIGINT,
	JOB_INSTANCE_ID BIGINT NOT NULL,
	CREATE_TIME TIMESTAMP(9) NOT NULL,
	START_TIME TIMESTAMP(9) DEFAULT NULL,
	END_TIME TIMESTAMP(9) DEFAULT NULL,
	STATUS VARCHAR(10),
	EXIT_CODE VARCHAR(2500),
	EXIT_MESSAGE VARCHAR(2500),
	LAST_UPDATED TIMESTAMP(9),
	constraint JOB_INST_EXEC_FK foreign key (JOB_INSTANCE_ID)
	references BATCH_JOB_INSTANCE(JOB_INSTANCE_ID)
) ;

CREATE TABLE IF NOT EXISTS BATCH_JOB_EXECUTION_PARAMS (
	JOB_EXECUTION_ID BIGINT NOT NULL,
	PARAMETER_NAME VARCHAR(100) NOT NULL,
	PARAMETER_TYPE VARCHAR(100) NOT NULL,
	PARAMETER_VALUE VARCHAR(2500),
	IDENTIFYING CHAR(1) NOT NULL,
	constraint JOB_EXEC_PARAMS_FK foreign key (JOB_EXECUTION_ID)
	references BATCH_JOB_EXECUTION(JOB_EXECUTION_ID)
) ;

CREATE TABLE IF NOT EXISTS BATCH_STEP_EXECUTION (
	STEP_EXECUTION_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	VERSION BIGINT NOT NULL,
	STEP_NAME VARCHAR(100) NOT NULL,
	JOB_EXECUTION_ID BIGINT NOT NULL,
	CREATE_TIME TIMESTAMP(9) NOT NULL,
	START_TIME TIMESTAMP(9) DEFAULT NULL,
	END_TIME TIMESTAMP(9) DEFAULT NULL,
	STATUS VARCHAR(10),
	COMMIT_COUNT BIGINT,
	READ_COUNT BIGINT,
	FILTER_COUNT BIGINT,
	WRITE_COUNT BIGINT,
	READ_SKIP_COUNT BIGINT,
	WRITE_SKIP_COUNT BIGINT,
	PROCESS_SKIP_COUNT BIGINT,
	ROLLBACK_COUNT BIGINT,
	EXIT_CODE VARCHAR(2500),
	EXIT_MESSAGE VARCHAR(2500),
	LAST_UPDATED TIMESTAMP(9),
	constraint JOB_EXEC_STEP_FK foreign key (JOB_EXECUTION_ID)
	references BATCH_JOB_EXECUTION(JOB_EXECUTION_ID)
) ;

CREATE TABLE IF NOT EXISTS BATCH_STEP_EXECUTION_CONTEXT (
	STEP_EXECUTION_ID BIGINT NOT NULL PRIMARY KEY,
	SHORT_CONTEXT VARCHAR(2500) NOT NULL,
	SERIALIZED_CONTEXT LONGVARCHAR,
	constraint STEP_EXEC_CTX_FK foreign key (STEP_EXECUTION_ID)
	references BATCH_STEP_EXECUTION(STEP_EXECUTION_ID)
) ;

CREATE TABLE IF NOT EXISTS BATCH_JOB_EXECUTION_CONTEXT (
	JOB_EXECUTION_ID BIGINT NOT NULL PRIMARY KEY,
	SHORT_CONTEXT VARCHAR(2500) NOT NULL,
	SERIALIZED_CONTEXT LONGVARCHAR,
	constraint JOB_EXEC_CTX_FK foreign key (JOB_EXECUTION_ID)
	references BATCH_JOB_EXECUTION(JOB_EXECUTION_ID)
) ;

CREATE SEQUENCE IF NOT EXISTS BATCH_STEP_EXECUTION_SEQ;
CREATE SEQUENCE IF NOT EXISTS BATCH_JOB_EXECUTION_SEQ;
CREATE SEQUENCE IF NOT EXISTS BATCH_JOB_INSTANCE_SEQ;

-- 로그인 계정(T10). 비밀번호는 DelegatingPasswordEncoder 해시({bcrypt}...)만 저장. SSO 계정은 password_hash 가 NULL
CREATE TABLE IF NOT EXISTS app_user (
    id            BIGINT AUTO_INCREMENT PRIMARY KEY,
    username      VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(200),
    display_name  VARCHAR(100) NOT NULL,
    roles         VARCHAR(100) NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    auth_source   VARCHAR(10)  NOT NULL DEFAULT 'LOCAL',
    failed_count  INT          NOT NULL DEFAULT 0,
    locked_until  TIMESTAMP,
    last_login_at TIMESTAMP,
    password_changed_at TIMESTAMP,
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 사용자 이름 사전(2단계). EXCEPT: 이름 아님(예외어), FORCE: 문맥 없이도 이름(추가 탐지어, 실명일 수 있음 → 설정자만 조회, 로그·감사에 단어 미기록)
CREATE TABLE IF NOT EXISTS name_dictionary (
    id         BIGINT AUTO_INCREMENT PRIMARY KEY,
    kind       VARCHAR(10)  NOT NULL,
    term       VARCHAR(50)  NOT NULL,
    created_by VARCHAR(100) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_name_dictionary UNIQUE (kind, term)
);

-- 교정 라벨(2단계): 미리보기에서 "이름 아님(NOT_PII) / 놓침(MISSED)" 표시. 원문은 저장하지 않고 원천 위치만 가리킨다.
-- row_fp: 저장 당시 원천 값의 HMAC 지문(CryptoService.fingerprint). 지금 값과 다르면 "원천 변경됨"으로 보고 쓰지 않는다
CREATE TABLE IF NOT EXISTS span_label (
    id            BIGINT AUTO_INCREMENT PRIMARY KEY,
    connection_id BIGINT       NOT NULL,
    source_table  VARCHAR(128) NOT NULL,
    pk_column     VARCHAR(128) NOT NULL,
    pk_value      VARCHAR(255) NOT NULL,
    column_name   VARCHAR(128) NOT NULL,
    start_pos     INT          NOT NULL,
    end_pos       INT          NOT NULL,
    label         VARCHAR(10)  NOT NULL,
    entity_type   VARCHAR(10)  NOT NULL,
    detector      VARCHAR(100),
    job_id        BIGINT,
    row_fp        VARCHAR(64)  NOT NULL,
    created_by    VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    -- 같은 자리에는 라벨 하나(이름 아님·놓침을 동시에 달 수 없음). 원천이 바뀐 라벨은 다시 달면 덮어쓴다(LabelService)
    CONSTRAINT uq_span_label_pos UNIQUE (connection_id, source_table, pk_value, column_name, start_pos, end_pos)
);
